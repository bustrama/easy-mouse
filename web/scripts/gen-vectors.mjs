// Generates tests/vectors.json from fixed inputs (only used when the file does not exist yet).
// Run: node scripts/gen-vectors.mjs   (from web/; Node 24 strips TypeScript types natively)
import { existsSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { bytesToHex } from '../src/protocol/b64.ts';
import {
  authMac,
  DIR_C2S,
  DIR_S2C,
  kdf,
  pairHelloMac,
  pairingCode,
  readyMac,
  sealFrame,
  sessionKeys,
  wrapSecret,
} from '../src/protocol/crypto.ts';
import { concatBytes } from '@noble/hashes/utils.js';
import { encMove, encState, encText } from '../src/protocol/ops.ts';

const out = fileURLToPath(new URL('../../tests/vectors.json', import.meta.url));
if (existsSync(out) && !process.argv.includes('--force')) {
  console.log(`${out} already exists; not overwriting`);
  process.exit(0);
}

const seq = (start, n) => Uint8Array.from({ length: n }, (_, i) => start + i);
const hex = bytesToHex;

const k = seq(0x00, 16);
const nc = seq(0x10, 16);
const ns = seq(0x20, 16);
const name = "Dana's iPhone";
const S = seq(0x40, 32);
const nc2 = seq(0x30, 16);
const ns2 = seq(0x50, 16);
const keys = sessionKeys(S, nc2, ns2);

const f1 = encMove(10, -5);
const f2 = encText('שלום')[0];
const f3 = encState({ pc: 'Office PC', volume: 62, muted: false, media: null });

const vectors = {
  description: 'Easy Mouse protocol vectors; all byte strings are lowercase hex. See docs/protocol.md. Generated by web/scripts/gen-vectors.mjs.',
  pairing: {
    k: hex(k),
    nc: hex(nc),
    ns: hex(ns),
    name,
    nameUtf8: hex(new TextEncoder().encode(name)),
    helloMac: hex(pairHelloMac(k, nc, name)),
    code: pairingCode(k, nc, ns),
    codeKey: hex(kdf(k, concatBytes(nc, ns), 'code')),
    wrapKey: hex(kdf(k, concatBytes(nc, ns), 'wrap')),
    secret: hex(S),
    wrap: hex(wrapSecret(k, nc, ns, S)),
  },
  connect: {
    secret: hex(S),
    nc: hex(nc2),
    ns: hex(ns2),
    authMac: hex(authMac(S, nc2, ns2)),
    readyMac: hex(readyMac(S, nc2, ns2)),
    kc2s: hex(keys.c2s),
    ks2c: hex(keys.s2c),
  },
  frames: [
    { dir: 'c2s', counter: 1, plaintext: hex(f1), frame: hex(sealFrame(keys.c2s, DIR_C2S, 1, f1)) },
    { dir: 'c2s', counter: 2, plaintext: hex(f2), frame: hex(sealFrame(keys.c2s, DIR_C2S, 2, f2)) },
    { dir: 's2c', counter: 1, plaintext: hex(f3), frame: hex(sealFrame(keys.s2c, DIR_S2C, 1, f3)) },
  ],
};

writeFileSync(out, JSON.stringify(vectors, null, 2) + '\n');
console.log(`wrote ${out}`);
