export const DICTS: Record<Lang, Record<Key, string>> = { en, he };

/** Pick the UI language from navigator.languages ("he", "iw" => Hebrew), defaulting to English. */
export function detectLang(languages: readonly string[]): Lang {
  for (const l of languages) {
    const base = l.toLowerCase().split('-')[0];
    if (base === 'he' || base === 'iw') return 'he';
    if (base === 'en') return 'en';
  }
  return 'en';
}

export function translate(lang: Lang, key: Key, params?: Record<string, string>): string {
  let s: string = DICTS[lang][key] ?? en[key];
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
